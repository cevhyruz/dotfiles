#!/usr/bin/env bash
# promptbuilder.sh - TUI to load, enable, edit and reorder bash prompt (PS1) segments.
# Built on tui.sh. Needs bash 4.4+ (the live preview uses ${var@P}).
#
#   ./promptbuilder.sh           open the editor
#   ./promptbuilder.sh --print   print the generated prompt file to stdout and exit
#
# Files (in ${XDG_CONFIG_HOME:-~/.config}/tui-prompt/):
#   segments.conf    your segment list      enabled|colour|name|content
#   segments.d/*.seg drop-in segments       same one-line format; loaded if the name is new
#   prompt.sh        generated, add to ~/.bashrc:   source ~/.config/tui-prompt/prompt.sh
#
# Segment content is a normal PS1 fragment: \u \h \w \A, $(command), ${VAR}.
# NOTE: the preview really runs $(command) parts, same as your prompt would.

(( BASH_VERSINFO[0] > 4 || (BASH_VERSINFO[0] == 4 && BASH_VERSINFO[1] >= 4) )) \
    || { echo "promptbuilder: needs bash 4.4+" >&2; exit 1; }

# _PB_HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# for _f in "${TUI_SH:-}" "$_PB_HERE/tui.sh" "$_PB_HERE/tui.bash"; do
#     [[ -n $_f && -f $_f ]] && { source "$_f"; break; }
# done

source "$_TUI_SOURCEPATH"

declare -F _tui_init >/dev/null \
    || { echo "promptbuilder: tui.sh not found (put it next to this script or set TUI_SH)" >&2; exit 1; }
shopt -s promptvars

_PB_DIR=${XDG_CONFIG_HOME:-$HOME/.config}/tui-prompt
_PB_CONF=$_PB_DIR/segments.conf
_PB_OUT=$_PB_DIR/prompt.sh

S_EN=() S_FG=() S_NAME=() S_CMD=()
_PB_SEP=' '
_PB_RC=0
_PB_DIRTY=0 _PB_HELP=0 _PB_QUIT=0 _PB_LROWS=3
_PB_PREVIEW= _PB_MSG=

# ---------------------------------------------------------------------------
# Helpers that also end up in the generated prompt file
# ---------------------------------------------------------------------------

__pb_rc()   { _PB_RC=$?; }
__pb_exit() { (( _PB_RC )) && printf '✘ %s' "$_PB_RC"; return 0; }
__pb_git() {
    local b
    b=$(git symbolic-ref --short -q HEAD 2>/dev/null || git rev-parse --short HEAD 2>/dev/null)
    [[ -n $b ]] && printf '⎇ %s' "$b"
    return 0
}

# ---------------------------------------------------------------------------
# Model: load / save / generate
# ---------------------------------------------------------------------------

_pb_add() { S_EN+=("$1"); S_FG+=("$2"); S_NAME+=("$3"); S_CMD+=("$4"); }

_pb_name_ok() {   # NAME SKIPIDX: non-empty, no '|', not used by another segment
    local i
    [[ -n $1 && $1 != *'|'* ]] || return 1
    for i in "${!S_NAME[@]}"; do
        (( i == $2 )) && continue
        [[ ${S_NAME[i]} == "$1" ]] && return 1
    done
    return 0
}

_pb_defaults() {
    _pb_add 1 196 exit  '$(__pb_exit)'
    _pb_add 1 114 user  '\u'
    _pb_add 0 180 host  '\h'
    _pb_add 1  75 cwd   '\w'
    _pb_add 1 176 git   '$(__pb_git)'
    _pb_add 0 141 venv  '${VIRTUAL_ENV:+(${VIRTUAL_ENV##*/})}'
    _pb_add 0 245 time  '\A'
    _pb_add 1 220 char  '\$'
}

_pb_parse_line() {   # LINE: add a segment if it parses and its name is new
    local en fg name cmd
    IFS='|' read -r en fg name cmd <<<"$1"
    [[ $en == [01] && $fg =~ ^[0-9]{1,3}$ ]] && (( 10#$fg <= 255 )) || return 1
    _pb_name_ok "$name" -1 || return 1
    _pb_add "$en" "$((10#$fg))" "$name" "$cmd"
}

_pb_load() {
    local line f
    S_EN=() S_FG=() S_NAME=() S_CMD=() _PB_SEP=' '
    if [[ -f $_PB_CONF ]]; then
        while IFS= read -r line || [[ -n $line ]]; do
            case $line in
                '#sep|'*) _PB_SEP=${line#'#sep|'} ;;
                ''|'#'*)  ;;
                *)        _pb_parse_line "$line" ;;
            esac
        done < "$_PB_CONF"
    else
        _pb_defaults
    fi
    for f in "$_PB_DIR"/segments.d/*.seg; do        # loader: drop-in segments
        [[ -f $f ]] || continue
        while IFS= read -r line || [[ -n $line ]]; do
            [[ -z $line || $line == '#'* ]] && continue
            _pb_parse_line "$line"
        done < "$f"
    done
}

# _pb_compose ps1|preview -> stdout. ps1 wraps colour codes in \[ \] for readline.
_pb_compose() {
    local i o= seg op= cl=
    [[ $1 == ps1 ]] && { op='\['; cl='\]'; }
    for i in "${!S_NAME[@]}"; do
        (( S_EN[i] )) || continue
        seg="${op}\\e[38;5;${S_FG[i]}m${cl}${S_CMD[i]}${op}\\e[0m${cl}"
        o+=${o:+$_PB_SEP}$seg
    done
    printf '%s ' "$o"
}

_pb_rebuild() {
    local p
    p=$(_pb_compose preview)
    { _PB_PREVIEW=${p@P}; } 2>/dev/null
}

_pb_write_prompt() {   # [PATH]
    local out=${1:-$_PB_OUT}
    {
        printf '# generated by promptbuilder.sh - edit with the tool, not by hand\n'
        printf '_PB_RC=0\n'
        declare -f __pb_rc __pb_exit __pb_git
        printf '%s\n' 'case ";${PROMPT_COMMAND-};" in *";__pb_rc;"*) ;; *) PROMPT_COMMAND="__pb_rc${PROMPT_COMMAND:+;$PROMPT_COMMAND}" ;; esac'
        printf 'PS1=%q\n' "$(_pb_compose ps1)"
    } > "$out"
}

_pb_save() {
    local i
    mkdir -p "$_PB_DIR" || { _PB_MSG="cannot create $_PB_DIR"; return 1; }
    {
        printf '#sep|%s\n' "$_PB_SEP"
        for i in "${!S_NAME[@]}"; do
            printf '%s|%s|%s|%s\n' "${S_EN[i]}" "${S_FG[i]}" "${S_NAME[i]}" "${S_CMD[i]}"
        done
    } > "$_PB_CONF" && _pb_write_prompt || { _PB_MSG="save failed"; return 1; }
    _PB_DIRTY=0
    _PB_MSG="saved. add to ~/.bashrc:  source $_PB_OUT"
}

# ---------------------------------------------------------------------------
# Editing actions
# ---------------------------------------------------------------------------

_pb_swap() {
    local a=$1 b=$2 t
    t=${S_EN[a]};   S_EN[a]=${S_EN[b]};     S_EN[b]=$t
    t=${S_FG[a]};   S_FG[a]=${S_FG[b]};     S_FG[b]=$t
    t=${S_NAME[a]}; S_NAME[a]=${S_NAME[b]}; S_NAME[b]=$t
    t=${S_CMD[a]};  S_CMD[a]=${S_CMD[b]};   S_CMD[b]=$t
}

_pb_toggle() {
    S_EN[_TUI_VSEL]=$(( 1 - S_EN[_TUI_VSEL] ))
    _PB_DIRTY=1; _pb_rebuild
}

_pb_move() {   # DIR (+1 / -1)
    local s=$_TUI_VSEL t=$(( _TUI_VSEL + $1 ))
    (( t < 0 || t >= ${#S_NAME[@]} )) && return 0
    _pb_swap "$s" "$t"; _TUI_VSEL=$t
    _PB_DIRTY=1; _pb_rebuild
}

_pb_cb_cmd() { S_CMD[_TUI_VSEL]=$1; _pb_rebuild; _pb_draw; }
_pb_cb_fg()  {
    if [[ $1 =~ ^[0-9]{1,3}$ ]] && (( 10#$1 <= 255 )); then S_FG[_TUI_VSEL]=$((10#$1)); fi
    _pb_rebuild; _pb_draw
}

_pb_edit_cmd() {
    local old=${S_CMD[_TUI_VSEL]}
    if _tui_readline 'content: ' "$old" '' _pb_cb_cmd; then
        S_CMD[_TUI_VSEL]=$_TUI_LINE
        [[ $_TUI_LINE != "$old" ]] && _PB_DIRTY=1
    else
        S_CMD[_TUI_VSEL]=$old
    fi
    _pb_rebuild
}

_pb_edit_fg() {
    local old=${S_FG[_TUI_VSEL]}
    if _tui_readline 'colour 0-255: ' "$old" '' _pb_cb_fg; then
        if [[ $_TUI_LINE =~ ^[0-9]{1,3}$ ]] && (( 10#$_TUI_LINE <= 255 )); then
            S_FG[_TUI_VSEL]=$((10#$_TUI_LINE))
            [[ ${S_FG[_TUI_VSEL]} != "$old" ]] && _PB_DIRTY=1
        else
            S_FG[_TUI_VSEL]=$old; _PB_MSG="colour must be 0-255"
        fi
    else
        S_FG[_TUI_VSEL]=$old
    fi
    _pb_rebuild
}

_pb_rename() {
    _tui_readline 'name: ' "${S_NAME[_TUI_VSEL]}" || return 0
    if _pb_name_ok "$_TUI_LINE" "$_TUI_VSEL"; then
        S_NAME[_TUI_VSEL]=$_TUI_LINE; _PB_DIRTY=1
    else
        _PB_MSG="name must be unique, non-empty, without '|'"
    fi
}

_pb_new() {
    local name
    _tui_readline 'new segment name: ' || return 0
    name=$_TUI_LINE
    _pb_name_ok "$name" -1 || { _PB_MSG="name must be unique, non-empty, without '|'"; return 0; }
    _tui_readline "content for $name: " || return 0
    _pb_add 1 252 "$name" "$_TUI_LINE"
    _TUI_VSEL=$(( ${#S_NAME[@]} - 1 ))
    _PB_DIRTY=1; _pb_rebuild
}

_pb_delete() {
    local s=$_TUI_VSEL
    _tui_confirm "delete '${S_NAME[s]}'?" || return 0
    S_EN=("${S_EN[@]:0:s}"     "${S_EN[@]:s+1}")
    S_FG=("${S_FG[@]:0:s}"     "${S_FG[@]:s+1}")
    S_NAME=("${S_NAME[@]:0:s}" "${S_NAME[@]:s+1}")
    S_CMD=("${S_CMD[@]:0:s}"   "${S_CMD[@]:s+1}")
    _PB_DIRTY=1; _pb_rebuild
}

_pb_sep() {
    _tui_readline 'separator: ' "$_PB_SEP" || return 0
    _PB_SEP=$_TUI_LINE; _PB_DIRTY=1; _pb_rebuild
}

# ---------------------------------------------------------------------------
# Drawing
# ---------------------------------------------------------------------------

_PB_HELPTXT=(
    "#|navigate"
    "j k|move selection (arrows, wheel, click)"
    "g G|first / last"
    "#|change"
    "space|enable / disable (or click the box)"
    "e|edit content (live preview)"
    "c|edit colour (0-255)"
    "n|rename"
    "a|add a new segment"
    "d|delete"
    "J K|move segment down / up"
    "p|edit separator"
    "x|preview a failed command (exit status)"
    "#|files"
    "s|save + generate prompt.sh"
    "r|reload from disk"
    "q|quit"
)

_pb_draw() {
    local n=${#S_NAME[@]} last=$(( _TUI_ROWS - 1 )) i r idx s box hint
    _PB_LROWS=$(( _TUI_ROWS - 8 )); (( _PB_LROWS < 1 )) && _PB_LROWS=1
    _tui_vp_fit "$_PB_LROWS" "$n"

    _tui_frame_begin
    _tui_resize_check && _tui_clear
    _tui_popup_hide help
    (( _PB_HELP )) && _tui_popup_geom_center help ${#_PB_HELPTXT[@]} 56
    _tui_popup_sync help

    if ! _tui_row_same 1 "t|$_TUI_COLS|$_PB_DIRTY"; then
        _tui_row_begin 1
        _tui_bold; _tui_fg 39; _tui_p ' prompt builder'; _tui_reset
        (( _PB_DIRTY )) && { _tui_fg 220; _tui_p '  ● unsaved'; _tui_reset; }
        _tui_clear_eol; _tui_row_end
    fi
    if ! _tui_row_same 2 "l|$_PB_RC|$_TUI_COLS"; then
        _tui_row_begin 2
        _tui_dim; _tui_p ' preview  (last exit status: %s)' "$_PB_RC"; _tui_reset
        _tui_clear_eol; _tui_row_end
    fi
    if ! _tui_row_same 3 "p|$_TUI_COLS|$_PB_PREVIEW"; then
        _tui_row_begin 3
        _tui_p '  %s' "$_PB_PREVIEW"; _tui_p '\e[7m \e[0m'
        _tui_clear_eol; _tui_row_end
    fi
    if ! _tui_row_same 4 "d|$_TUI_COLS"; then
        _tui_row_begin 4; _tui_dim; _tui_hline 4 1 "$_TUI_COLS"; _tui_reset; _tui_clear_eol; _tui_row_end
    fi

    for (( i = 0; i < _PB_LROWS; i++ )); do
        r=$(( 5 + i )) idx=$(( _TUI_VTOP + i ))
        if (( idx >= n )); then
            _tui_row_same "$r" "e|$_TUI_COLS" && continue
            _tui_row_begin "$r"; _tui_clear_eol; _tui_row_end
            continue
        fi
        s=0; (( idx == _TUI_VSEL )) && s=1
        _tui_row_same "$r" "$idx|$s|${S_EN[idx]}|${S_FG[idx]}|${S_NAME[idx]}|${S_CMD[idx]}|$_TUI_COLS" && continue
        box='[ ]'; (( S_EN[idx] )) && box='[x]'
        _tui_row_begin "$r"
        (( s )) && _tui_reverse
        (( S_EN[idx] )) || _tui_dim
        _tui_p ' %s %-10.10s ' "$box" "${S_NAME[idx]}"
        _tui_fg "${S_FG[idx]}"; _tui_p '■'; _tui_p '\e[39m %3d  %s' "${S_FG[idx]}" "${S_CMD[idx]:0:_TUI_COLS-24}"
        _tui_clear_eol; _tui_reset; _tui_row_end
    done

    if ! _tui_row_same $(( last - 2 )) "d|$_TUI_COLS"; then
        _tui_row_begin $(( last - 2 )); _tui_dim; _tui_hline $(( last - 2 )) 1 "$_TUI_COLS"; _tui_reset
        _tui_clear_eol; _tui_row_end
    fi
    _tui_kv_row $(( last - 1 )) content "${S_CMD[_TUI_VSEL]-}"
    _tui_kv_row "$last" output "${_PB_OUT}${_PB_DIRTY:+$( (( _PB_DIRTY )) && printf '  (unsaved changes)')}"

    _tui_popup_draw help ' keys ' _PB_HELPTXT 9 114 cut

    hint='space toggle  e edit  c colour  a add  d del  J/K move  s save  ? help  q quit'
    _tui_status "${_TUI_PROMPT:-${_PB_MSG:-$hint}}"
    _tui_frame_end
}

# ---------------------------------------------------------------------------
# Input handling
# ---------------------------------------------------------------------------

_pb_handle() {
    local n=${#S_NAME[@]} y x idx
    _PB_MSG=
    case $_TUI_KEY in
        '?')            _PB_HELP=1 ;;
        a)              _pb_new ;;
        p)              _pb_sep ;;
        x)              (( _PB_RC = _PB_RC ? 0 : 1 )); _pb_rebuild ;;
        s)              _pb_save ;;
        r)              if (( ! _PB_DIRTY )) || _tui_confirm 'discard unsaved changes?'; then
                            _pb_load; _pb_rebuild; _PB_DIRTY=0; _PB_MSG="reloaded"
                        fi ;;
        q)              if (( ! _PB_DIRTY )) || _tui_confirm 'quit without saving?'; then _PB_QUIT=1; fi ;;
        wheelup)        _tui_vp_scroll -3 "$_PB_LROWS" "$n" ;;
        wheeldown)      _tui_vp_scroll 3 "$_PB_LROWS" "$n" ;;
        click)          y=$_TUI_MY x=$_TUI_MX
                        if (( n && y >= 5 && y < 5 + _PB_LROWS )); then
                            idx=$(( _TUI_VTOP + y - 5 ))
                            if (( idx < n )); then
                                _TUI_VSEL=$idx
                                (( x >= 2 && x <= 4 )) && _pb_toggle
                            fi
                        fi ;;
    esac
    (( n )) || return 0
    case $_TUI_KEY in
        j|down)         (( _TUI_VSEL < n - 1 )) && (( _TUI_VSEL++ )) ;;
        k|up)           (( _TUI_VSEL > 0 )) && (( _TUI_VSEL-- )) ;;
        g)              _TUI_VSEL=0 ;;
        G)              _TUI_VSEL=$(( n - 1 )) ;;
        space|enter)    _pb_toggle ;;
        J)              _pb_move 1 ;;
        K)              _pb_move -1 ;;
        e)              _pb_edit_cmd ;;
        c)              _pb_edit_fg ;;
        n)              _pb_rename ;;
        d)              _pb_delete ;;
    esac
    return 0
}

_pb_main() {
    _pb_load; _pb_rebuild
    trap '_tui_deinit' EXIT
    _tui_trap_resize
    _tui_init
    _tui_mouse_on
    _TUI_REDRAW=_pb_draw
    while :; do
        _tui_pending || _pb_draw
        _tui_key "$_TUI_TICK" || break
        [[ -z $_TUI_KEY ]] && continue
        if (( _PB_HELP )); then _PB_HELP=0; continue; fi
        _pb_handle
        (( _PB_QUIT )) && break
    done
}

case ${1-} in
    --print)  _pb_load; _pb_write_prompt /dev/stdout ;;
    -h|--help) sed -n '2,13p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//' ;;
    *)        _pb_main ;;
esac
